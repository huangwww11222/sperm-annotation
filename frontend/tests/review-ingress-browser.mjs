import assert from 'node:assert/strict'
import fs from 'node:fs'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fixture=JSON.parse(fs.readFileSync('work/browser-fixture.json'))
const origin=process.env.REVIEW_ORIGIN || 'http://127.0.0.1:5373'
const browser=await chromium.launch({channel:'chrome',headless:true})
const page=await browser.newPage({viewport:{width:1600,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(String(e)))
try{
 await page.addInitScript(({authorToken})=>{localStorage.setItem('rare-sperm-token',authorToken);localStorage.setItem('rare-sperm-auth',JSON.stringify({id:'1',name:'review-A'}))},fixture)
 await page.goto(origin+'/annotate')
 await page.getByRole('button',{name:/VID review-fixture.avi/}).click()
 await page.getByRole('button',{name:'完成标注并送审',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'完成标注并送审'})
 await dialog.getByText('全视频 3 帧：有对象 2 帧，已明确空帧 1 帧，未知 0 帧。',{exact:true}).waitFor()
 console.log('PASS saved workspace and real tracking results are previewed together')
 assert(await dialog.getByRole('button',{name:'确认送审',exact:true}).isDisabled())
 console.log('PASS annotation completion requires explicit A confirmation')
 await dialog.getByRole('checkbox').check()
 const result=page.waitForResponse(r=>r.url().includes('/complete')&&r.request().method()==='POST')
 await dialog.getByRole('button',{name:'确认送审',exact:true}).click()
 const response=await result;assert.equal(response.status(),200,await response.text())
 const data=await response.json()
 await dialog.getByRole('status').waitFor()
 assert.equal(data.session.state,'pending');assert.equal(data.session.frameCount,3)
 console.log('PASS complete A and pending B task created from existing source')
 const r=await page.request.get(`${origin}/api/review/sessions/${data.session.id}`,{headers:{Authorization:'Bearer '+fixture.token}})
 assert.equal((await r.json()).permissions.canClaim,true)
 console.log('PASS another reviewer can claim the created task')
 const fr=await page.request.get(`${origin}/api/review/sessions/${data.session.id}/frames/0`,{headers:{Authorization:'Bearer '+fixture.token}})
 const f=await fr.json();assert.equal(f.baselineObjects.length,2)
 assert.deepEqual(f.baselineObjects[0].bbox,[200,140,260,200])
 console.log('PASS real AI annotation identity and pixel coordinates are preserved')
 await page.screenshot({path:'output/playwright/review-ingress.png',fullPage:true})
 assert.deepEqual(errors,[]);console.log('PASS ingress has no JavaScript runtime exceptions')
}finally{await browser.close()}
